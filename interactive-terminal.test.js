'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('public/js/app.js', 'utf8');
const html = fs.readFileSync('public/index.html', 'utf8');
const css = fs.readFileSync('public/css/styles.css', 'utf8');
const gateway = fs.readFileSync('interactive-runner/gateway.js', 'utf8');
const sessionRunner = fs.readFileSync('interactive-runner/session-runner.js', 'utf8');
const catalog = require('./src/compiler/LanguageRegistry').LANGUAGES;
const runnerLanguages = require('./runner/languages.json');
const runtimeIds = new Set(runnerLanguages.map(x => x.id));
const sqlRuntime = runnerLanguages.find(item => item.id === 'sql');
assert.ok(sqlRuntime && sqlRuntime.run.includes('-cmd') && sqlRuntime.run.some(value => value.includes('.read /work/main.sql')), 'SQL source must load before the SQLite CLI reads interactive stdin.');
const jqRuntime = runnerLanguages.find(item => item.id === 'jq');
assert.ok(jqRuntime && !jqRuntime.run.includes('-n'), 'jq must consume terminal stdin instead of running in null-input mode.');

assert.equal(Object.keys(catalog).length, 55, 'The original 55-language catalogue must remain intact.');
for (const id of Object.keys(catalog)) assert.ok(runtimeIds.has(id), `Interactive runtime missing for ${id}`);
assert.match(app, /function ensureTerminalInput\(\)/, 'Input must be typed in the integrated terminal.');
assert.match(app, /type: 'input', data: value, newline: withNewline/, 'Terminal input must be forwarded to the running process stdin.');
assert.match(app, /type: 'eof'/, 'Terminal must support EOF.');
assert.match(app, /type: 'stop'/, 'Terminal must support interrupt/cancel.');
assert.match(app, /type: 'eof'/, 'Terminal must support EOF.');
const clearConsoleBody = app.slice(app.indexOf('function clearConsole()'), app.indexOf('clearConsoleBtn.addEventListener'));
assert.doesNotMatch(clearConsoleBody, /closeInteractiveSession|currentAbortCtrl\.abort/, 'Clear Output must not stop the running program.');
assert.match(app, /toLocaleTimeString\(\)/, 'Each execution must show a timestamp.');
assert.match(app, /setRunButtonResult\(/, 'Run button must expose success and failure states.');
assert.doesNotMatch(app, /function showBatchInput\(/, 'A separate stdin textarea fallback must not exist.');
assert.doesNotMatch(app, /Run with this input/, 'A separate Run-with-input control must not exist.');
assert.match(app, /function showInteractiveUnavailable\(reason = ''\)/, 'Missing live gateway must be reported without a fake stdin field.');
assert.match(app, /showInteractiveUnavailable\(ticketData\.userMessage \|\| ticketData\.error/, 'The terminal must show actionable backend gateway configuration errors.');
assert.match(html, /type directly on the terminal prompt/i, 'The output panel must explain terminal-based input.');
assert.match(css, /\.console-output\.terminal-window[\s\S]*overflow-x:\s*auto/, 'The terminal must support horizontal scrolling.');
assert.match(sessionRunner, /stty -echo/, 'PTY line-discipline echo must be disabled.');
assert.match(sessionRunner, /--echo', 'never'/, 'script must never echo early input before stty has run; this prevents a ready-event race.');
assert.match(sessionRunner, /MAX_QUEUED_INPUT_BYTES/, 'Input arriving before runtime startup must be safely queued.');
assert.match(sessionRunner, /memoryBytes: readPeakMemoryBytes\(\)/, 'Interactive runs should report cgroup peak memory when available.');
assert.match(fs.readFileSync('runner/js-runner.js', 'utf8'), /global\.prompt/, 'JavaScript and TypeScript prompt() calls must read from terminal stdin.');
assert.match(gateway, /'--network', 'none'/, 'Untrusted code must run without network access.');
assert.match(gateway, /'--memory', '1g'/, 'The execution container must have a bounded memory limit.');
assert.match(gateway, /usedTickets/, 'Interactive tickets must be single-use.');
assert.match(gateway, /docker-daemon-unavailable/, 'Gateway readiness must fail when the Docker daemon is unavailable.');
assert.match(gateway, /execution-image-missing/, 'Gateway readiness must fail when the runtime image is missing.');
assert.match(gateway, /\['rm', '-f', containerName\]/, 'Cancelling a run must remove the actual Docker container.');
console.log('[PASS] Integrated terminal has inline live stdin, EOF, interrupt, paste and no separate stdin textbox.');
console.log(`[PASS] All ${Object.keys(catalog).length} catalogue languages have interactive runtime definitions.`);
console.log('[PASS] Runtime sessions use a PTY, bounded sandbox, timeout, input queue and cleanup controls.');
